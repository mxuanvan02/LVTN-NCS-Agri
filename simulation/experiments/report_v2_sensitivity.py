#!/usr/bin/env python3
"""Generate descriptive v2 sensitivity summaries and a LaTeX table.

The sensitivity grid is exploratory and separate from primary inference. Means
are pooled descriptively over six network profiles and 15 seeds (n=90 per
plant/setting). Oracle rows are sensitivity-only and are never primary input.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "results/v2_sensitivity_raw.csv"
OUT = ROOT / "results/v2_sensitivity_summary.csv"
METRICS = ["nrmse", "violation_pct", "transmissions", "total_modeled_energy_mj"]
ORDER = [
    "forecast_persistence", "trigger_0.02", "trigger_0.07",
    "forecast_noisy_persistence", "forecast_oracle", "model_0.98",
    "model_1.02", "buffer_no_buffer",
]
LABEL = {
    "forecast_persistence": "Cơ sở: persistence, $\\delta=0{,}035$",
    "trigger_0.02": "$\\delta=0{,}02$",
    "trigger_0.07": "$\\delta=0{,}07$",
    "forecast_noisy_persistence": "Dự báo persistence có nhiễu",
    "forecast_oracle": "Oracle (chỉ độ nhạy)",
    "model_0.98": "Sai lệch mô hình dự báo $0{,}98$",
    "model_1.02": "Sai lệch mô hình dự báo $1{,}02$",
    "buffer_no_buffer": "Không giữ lệnh (zero fallback)",
}
PLANT = {"greenhouse": "Nhà kính", "irrigation": "Tưới tổng hợp"}

def fmt(x: float, digits: int = 3) -> str:
    return f"{x:.{digits}f}".replace(".", ",")

def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tex", type=Path, help="optional generated LaTeX fragment")
    args = ap.parse_args()
    raw = pd.read_csv(RAW)
    assert len(raw) == 1800
    assert set(raw["forecast"]) >= {"persistence", "noisy_persistence", "oracle"}
    grouped = raw.groupby(["plant", "setting_id"], as_index=False).agg(
        n_runs=("seed", "size"), n_seeds=("seed", "nunique"),
        n_networks=("network", "nunique"),
        **{f"{m}_mean": (m, "mean") for m in METRICS},
        **{f"{m}_sd": (m, "std") for m in METRICS},
    )
    grouped["analysis_scope"] = "exploratory_sensitivity_only"
    grouped.to_csv(OUT, index=False)
    if args.tex:
        rows = []
        for plant in ("greenhouse", "irrigation"):
            for setting in ORDER:
                r = grouped[(grouped.plant == plant) & (grouped.setting_id == setting)].iloc[0]
                rows.append(
                    f"{PLANT[plant]} & {LABEL[setting]} & {int(r.n_runs)} & "
                    f"{fmt(r.nrmse_mean)} & {fmt(r.violation_pct_mean,1)} & "
                    f"{fmt(r.transmissions_mean,1)} & {fmt(r.total_modeled_energy_mj_mean,1)} \\\\"
                )
        tex = r"""% AUTO-GENERATED by experiments/report_v2_sensitivity.py; do not hand edit.
\begin{table}[tbp]
\centering
\caption{Phân tích độ nhạy mô tả của ET--MPC từ 1.800 lượt chạy riêng biệt; mỗi hàng gộp sáu cấu hình mạng và 15 hạt giống (90 lượt), không thuộc suy luận primary. Hai hàng sai lệch mô hình chỉ nhân hệ số vào mô hình dự báo bên trong bộ điều khiển, còn động học plant mô phỏng giữ nguyên}
\label{tab:v2_sensitivity_results}
\scriptsize
\setlength{\tabcolsep}{2.5pt}
\renewcommand{\arraystretch}{1.05}
\resizebox{\textwidth}{!}{%
\begin{tabular}{|l|l|r|r|r|r|r|}
\hline
\textbf{Plant} & \textbf{Thiết lập độ nhạy} & \textbf{$n$} & \textbf{NRMSE} & \textbf{Vi phạm (\%)} & \textbf{Số truyền} & \textbf{Năng lượng mô hình (mJ)} \\ \hline
""" + "\n".join(row + " \\hline" for row in rows) + r"""
\end{tabular}}
\end{table}
"""
        args.tex.parent.mkdir(parents=True, exist_ok=True)
        args.tex.write_text(tex, encoding="utf-8")
    print(f"sensitivity_rows={len(raw)} summary_rows={len(grouped)} oracle_rows={sum(raw.setting_id=='forecast_oracle')}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
